const LOCALES = { he, en, ar, ru, uk, fr, es };
const FALLBACK_CHAIN = ['en', 'he'];

function interpolate(template, vars) {
  if (!vars) return template;
  return String(template).replace(/\{(\w+)\}/g, (match, key) =>
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : match
  );
}

/** תרגום מפתח ULTRA. מקבל קוד שפה (או כל ערך — ברירת מחדל עברית). */
function ut(lang, key, vars) {
  const base = String(lang || 'he').toLowerCase().split('-')[0];
  const chain = [LOCALES[base] ? base : 'he', ...FALLBACK_CHAIN];
  for (const code of chain) {
    const dict = LOCALES[code];
    if (dict && dict[key] !== undefined) return interpolate(dict[key], vars);
  }
  return key;
}

/** יוצר פונקציית תרגום צמודה לשפה. */
function translator(lang) {
  const fn = (key, vars) => ut(lang, key, vars);
  fn.lang = lang;
  return fn;
}

